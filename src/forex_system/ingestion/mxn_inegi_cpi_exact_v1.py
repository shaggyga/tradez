def _read_and_verify_pdf_text(artifact_id: str) -> str:
    spec = _ARTIFACT_SPECS[artifact_id]
    raw = _read_artifact(artifact_id)
    extracted, page_count = _normalized_pdf_text(raw)
    if page_count != spec["page_count"]:
        _fail(f"pdf_page_count_mismatch:{artifact_id}")
    if len(extracted) != spec["text_bytes"]:
        _fail(f"pdf_text_byte_count_mismatch:{artifact_id}")
    if hashlib.sha256(extracted).hexdigest() != spec["text_sha256"]:
        _fail(f"pdf_text_sha256_mismatch:{artifact_id}")
    text_path = _workspace_path(spec["text_path"])
    retained = _read_exact_pinned_file(
        text_path,
        expected_path=text_path,
        expected_bytes=spec["text_bytes"],
        expected_sha256=spec["text_sha256"],
    )
    if retained != extracted:
        _fail(f"pdf_retained_text_not_reproducible:{artifact_id}")
    return extracted.decode("utf-8")


def _scheduled_utc(event_date: str) -> dt.datetime:
    local = dt.datetime.fromisoformat(f"{event_date}T06:00:00").replace(
        tzinfo=ZoneInfo(TIMEZONE_NAME)
    )
    if local.utcoffset() != dt.timedelta(hours=-6) or local.dst() != dt.timedelta(0):
        _fail("mexico_city_2026_timezone_contract_failed")
    return local.astimezone(UTC)


def _iso_z(value: dt.datetime) -> str:
    return value.astimezone(UTC).isoformat().replace("+00:00", "Z")


def _event_id(event_date: str) -> str:
    return f"mxn_inegi_cpi_release:{event_date}"


def _episode_key(event_date: str) -> str:
    return f"MXN:inegi_cpi_release:{event_date}"


def _guardrails() -> dict[str, Any]:
    return dict(_GUARDRAILS)


def _assert_guardrails(value: Mapping[str, Any]) -> None:
    for key, expected in _GUARDRAILS.items():
        if not _strict_equal(value.get(key), expected):
            _fail(f"guardrail_violation:{key}")
    forbidden = {
        "expected_net_pips",
        "forecast_mean_bps",
        "allocator_rank",
        "trade_side",
        "signal_direction",
        "raw_pdf",
        "raw_xml",
        "full_text",
    }
    overlap = forbidden.intersection(value)
    if overlap:
        _fail(f"forbidden_output_surface:{','.join(sorted(overlap))}")


def _parse_calendar(manifest: Mapping[str, Any]) -> list[dict[str, Any]]:
    text = _read_and_verify_pdf_text("calendar_pdf")
    pages = text.split("\n\f\n")
    target_pages = [
        page
        for page in pages
        if "Índice Nacional de Precios al Consumidor, 2.ª quincena y mensual." in page
    ]
    if len(target_pages) != 1:
        _fail("calendar_target_section_missing_or_ambiguous")
    page = re.sub(r"\s+", " ", target_pages[0])
    if "la información se difunde a las 06:00 a.m." not in page:
        _fail("calendar_release_time_missing")
    target_heading = "Índice Nacional de Precios al Consumidor, 2.ª quincena y mensual."
    next_heading = "Índice Nacional de Precios Productor (INPP)"
    start = page.find(target_heading)
    end = page.find(next_heading, start + len(target_heading))
    if start < 0 or end <= start:
        _fail("calendar_target_section_boundary_missing")
    target_section = page[start:end]
    pairs = (("07/agosto", "Julio"), ("09/septiembre", "Agosto"))
    for date_label, period_label in pairs:
        if len(
            re.findall(
                rf"\b{re.escape(date_label)}\s+{period_label}\b", target_section
            )
        ) != 1:
            _fail(f"calendar_date_period_missing_or_ambiguous:{date_label}")

    artifacts = _artifact_map(manifest)
    observed_text = artifacts["calendar_pdf"]["observed_utc"]
    observed = _canonical_utc(observed_text, label="calendar_pdf_observed_utc")
    rows: list[dict[str, Any]] = []
    for expected in EXPECTED_CLOCKS:
        scheduled = _scheduled_utc(expected["event_date"])
        if _iso_z(scheduled) != expected["scheduled_utc"]:
            _fail("calendar_utc_derivation_mismatch")
        captured_pre_event = observed < scheduled
        historical = expected["event_date"] == "2026-08-07"
        prospective_schedule = not historical and captured_pre_event
        collection_class = (
            "historical_availability_counterfactual_archive_only"
            if historical
            else "prospective_schedule_only"
            if captured_pre_event
            else "late_schedule_capture_archive_only"
        )
        if collection_class != expected["collection_class"]:
            _fail("calendar_collection_class_mismatch")
        row = {
            "schema_version": SCHEMA_VERSION,
            "source_id": SOURCE_ID,
            "source_contract_id": CONTRACT_ID,
            "source_cohort_id": COHORT_ID,
            "event_id": _event_id(expected["event_date"]),
            "event_series_id": "mxn_inegi_cpi_release",
            "event_date": expected["event_date"],
            "reference_period": expected["reference_period"],
            "currency": "MXN",
            "currency_factor": "MXN",
            "independent_episode_key": _episode_key(expected["event_date"]),
            "local_timezone": TIMEZONE_NAME,
            "local_time": expected["local_time"],
            "scheduled_utc": expected["scheduled_utc"],
            "calendar_observed_utc": observed_text,
            "calendar_captured_pre_event": captured_pre_event,
            "prospective_schedule": prospective_schedule,
            "collection_class": collection_class,
            "calendar_source_url": CALENDAR_PDF_URL,
            "calendar_source_sha256": _ARTIFACT_SPECS["calendar_pdf"]["sha256"],
            "calendar_source_bytes": _ARTIFACT_SPECS["calendar_pdf"]["bytes"],
            "calendar_text_sha256": _ARTIFACT_SPECS["calendar_pdf"]["text_sha256"],
            "calendar_xml_used": False,
            "calendar_xml_prior_snapshot_backfilled": False,
            **_guardrails(),
        }
        _assert_guardrails(row)
        rows.append(row)
    return rows


def _parse_decimal(value: str, *, label: str) -> Decimal:
    try:
        parsed = Decimal(value)
    except InvalidOperation as exc:
        raise MxnInegiCpiExactSourceError(f"{label}_invalid_decimal") from exc
    if not parsed.is_finite():
        _fail(f"{label}_nonfinite")
    return parsed


def _parse_xml_fact(artifact_id: str) -> tuple[str, Decimal]:
    spec = _ARTIFACT_SPECS[artifact_id]
    raw = _read_artifact(artifact_id)
    try:
        root = ET.fromstring(raw)
    except ET.ParseError as exc:
        raise MxnInegiCpiExactSourceError(f"xml_parse_failed:{artifact_id}") from exc
    if root.tag != "DATASET" or root.attrib or len(root) != 2:
        _fail(f"xml_root_contract_mismatch:{artifact_id}")
    metadata, series = root
    if metadata.tag != "METADATA" or metadata.attrib:
        _fail(f"xml_metadata_contract_mismatch:{artifact_id}")
    if series.tag != "SERIE" or series.attrib or len(series) != 1:
        _fail(f"xml_series_contract_mismatch:{artifact_id}")
    expected_tags = [
        "Nemonic",
        "Name",
        "Name",
        "Unit",
        "Unit",
        "Freq",
        "Freq",
        "NoOfDecimals",
        "LastUpdate",
        "CreationDate",
    ]
    if [child.tag for child in metadata] != expected_tags:
        _fail(f"xml_metadata_membership_mismatch:{artifact_id}")
    values = {child.tag: (child.text or "").strip() for child in metadata if child.tag not in {"Name", "Unit", "Freq"}}
    if values != {
        "Nemonic": spec["nemonic"],
        "NoOfDecimals": "3",
        "LastUpdate": "07/08/2026",
        "CreationDate": "07/08/2026",
    }:
        _fail(f"xml_metadata_value_mismatch:{artifact_id}")
    for child in metadata:
        if child.tag in {"Name", "Unit", "Freq"}:
            if set(child.attrib) != {"{http://www.w3.org/XML/1998/namespace}lang"}:
                _fail(f"xml_language_attribute_mismatch:{artifact_id}")
            if child.attrib["{http://www.w3.org/XML/1998/namespace}lang"] not in {"en", "es"}:
                _fail(f"xml_language_value_mismatch:{artifact_id}")
        elif child.attrib:
            _fail(f"xml_unexpected_metadata_attribute:{artifact_id}")
    obs = series[0]
    if obs.tag != "Obs" or len(obs) != 0 or set(obs.attrib) != {"TimePeriod", "CurrentValue"}:
        _fail(f"xml_observation_contract_mismatch:{artifact_id}")
    if (obs.text or "").strip() or obs.tail and obs.tail.strip():
        _fail(f"xml_observation_text_forbidden:{artifact_id}")
    if obs.attrib["TimePeriod"] != "2026/07":
        _fail(f"xml_reference_period_mismatch:{artifact_id}")
    parsed_raw = _parse_decimal(obs.attrib["CurrentValue"], label=artifact_id)
    # INEGI declares three decimals but serializes binary-float tails in the
    # current-value attribute.  Normalize only to that explicit source
    # precision; retain the raw bytes and never round beyond the declared unit.
    parsed = parsed_raw.quantize(Decimal("0.001"))
    expected = EXPECTED_JULY_FACTS[spec["fact_name"]]
    if parsed != expected.quantize(Decimal("0.001")):
        _fail(f"xml_fact_value_mismatch:{artifact_id}")
    return spec["fact_name"], expected


def _extract_unique_decimal(text: str, pattern: str, *, label: str) -> Decimal:
    matches = re.findall(pattern, text, flags=re.IGNORECASE)
    if len(matches) != 1:
        _fail(f"pdf_fact_missing_or_ambiguous:{label}")
    return _parse_decimal(matches[0], label=label)


def _parse_release_pdf_facts() -> dict[str, Decimal]:
    text = _read_and_verify_pdf_text("july_release_pdf")
    collapsed = re.sub(r"\s+", " ", text)
    if len(re.findall(r"7 de agosto de 2026", collapsed, flags=re.IGNORECASE)) != 6:
        _fail("release_pdf_date_or_page_count_mismatch")
    if "ÍNDICE NACIONAL DE PRECIOS AL CONSUMIDOR (INPC)" not in collapsed.upper():
        _fail("release_pdf_title_missing")
    facts = {
        "headline_monthly_pct": _extract_unique_decimal(
            collapsed,
            r"aumentó\s+([0-9]+(?:\.[0-9]+)?)\s*%\s+respecto al mes anterior",
            label="headline_monthly_pct",
        ),
        "headline_annual_pct": _extract_unique_decimal(
            collapsed,
            r"inflación general anual se ubicó en\s+([0-9]+(?:\.[0-9]+)?)\s+por ciento",
            label="headline_annual_pct",
        ),
        "core_monthly_pct": _extract_unique_decimal(
            collapsed,
            r"índice de precios subyacente.*?creció\s+([0-9]+(?:\.[0-9]+)?)\s*%\s+a tasa mensual",
            label="core_monthly_pct",
        ),
        "core_annual_pct": _extract_unique_decimal(
            collapsed,
            r"A tasa anual,\s+en\s+julio pasado,\s+los\s+índices\s+subyacente\s+y\s+no subyacente\s+ascendieron\s+([0-9]+(?:\.[0-9]+)?)\s+y",
            label="core_annual_pct",
        ),
    }
    if facts != EXPECTED_JULY_FACTS:
        _fail("release_pdf_fact_bundle_mismatch")
    return facts


def _parse_july_release(
    manifest: Mapping[str, Any], calendar: list[dict[str, Any]]
) -> dict[str, Any]:
    calendar_rows = [row for row in calendar if row["event_date"] == "2026-08-07"]
    if len(calendar_rows) != 1:
        _fail("july_calendar_event_not_unique")
    calendar_event = calendar_rows[0]
    pdf_facts = _parse_release_pdf_facts()
    xml_facts: dict[str, Decimal] = {}
    for artifact_id in (
        "headline_annual_xml",
        "headline_monthly_xml",
        "core_annual_xml",
        "core_monthly_xml",
    ):
        name, value = _parse_xml_fact(artifact_id)
        if name in xml_facts:
            _fail("duplicate_xml_fact")
        xml_facts[name] = value
    if xml_facts != pdf_facts or xml_facts != EXPECTED_JULY_FACTS:
        _fail("pdf_xml_corroboration_mismatch")

    artifacts = _artifact_map(manifest)
    fact_observations = [
        _canonical_utc(artifacts[artifact_id]["observed_utc"], label=f"{artifact_id}_observed")
        for artifact_id in (
            "july_release_pdf",
            "headline_annual_xml",
            "headline_monthly_xml",
            "core_annual_xml",
            "core_monthly_xml",
        )
    ]
    known = max(fact_observations)
    scheduled = dt.datetime.fromisoformat(
        calendar_event["scheduled_utc"].replace("Z", "+00:00")
    )
    if known <= scheduled:
        _fail("historical_july_knowledge_time_not_after_release")
    facts_serialized = {key: str(value) for key, value in EXPECTED_JULY_FACTS.items()}
    record = {
        "schema_version": SCHEMA_VERSION,
        "source_id": SOURCE_ID,
        "source_contract_id": CONTRACT_ID,
        "source_cohort_id": COHORT_ID,
        "event_id": _event_id("2026-08-07"),
        "event_series_id": "mxn_inegi_cpi_release",
        "event_date": "2026-08-07",
        "reference_period": "2026-07",
        "currency": "MXN",
        "currency_factor": "MXN",
        "independent_episode_key": _episode_key("2026-08-07"),
        "scheduled_utc": calendar_event["scheduled_utc"],
        "fact_bundle_known_utc": known.isoformat(),
        "collection_class": "historical_availability_counterfactual_archive_only",
        "historical_availability_counterfactual": True,
        "prospective_observation": False,
        "facts": facts_serialized,
        "facts_sha256": canonical_sha256(facts_serialized),
        "pdf_xml_corroborated": True,
        "calendar_source_sha256": _ARTIFACT_SPECS["calendar_pdf"]["sha256"],
        "release_pdf_sha256": _ARTIFACT_SPECS["july_release_pdf"]["sha256"],
        "release_pdf_text_sha256": _ARTIFACT_SPECS["july_release_pdf"]["text_sha256"],
        "xml_source_sha256": {
            artifact_id: _ARTIFACT_SPECS[artifact_id]["sha256"]
            for artifact_id in (
                "headline_annual_xml",
                "headline_monthly_xml",
                "core_annual_xml",
                "core_monthly_xml",
            )
        },
        "calendar_xml_used": False,
        "calendar_xml_later_revision_quarantined": True,
        **_guardrails(),
    }
    _assert_guardrails(record)
    return record


