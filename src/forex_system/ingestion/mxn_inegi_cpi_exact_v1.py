class MxnInegiCpiExactSourceError(RuntimeError):
    """Raised whenever the exact retained-source contract is not proved."""


def _fail(reason: str) -> None:
    raise MxnInegiCpiExactSourceError(reason)


def _canonical_json(value: Any) -> str:
    return json.dumps(
        value,
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=True,
        allow_nan=False,
    )


def canonical_sha256(value: Any) -> str:
    return hashlib.sha256(_canonical_json(value).encode("utf-8")).hexdigest()


def _strict_equal(actual: Any, expected: Any) -> bool:
    if type(expected) is dict:
        if type(actual) is not dict or set(actual) != set(expected):
            return False
        return all(_strict_equal(actual[key], value) for key, value in expected.items())
    if type(expected) in (list, tuple):
        if type(actual) not in (list, tuple) or len(actual) != len(expected):
            return False
        return all(_strict_equal(left, right) for left, right in zip(actual, expected))
    if expected is None:
        return actual is None
    return type(actual) is type(expected) and actual == expected


def _strict_json(raw: bytes, *, label: str) -> Any:
    def reject_constant(value: str) -> None:
        _fail(f"{label}_nonfinite_number:{value}")

    def parse_float(value: str) -> float:
        parsed = float(value)
        if not math.isfinite(parsed):
            _fail(f"{label}_nonfinite_number:{value}")
        return parsed

    def unique_object(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
        result: dict[str, Any] = {}
        for key, value in pairs:
            if key in result:
                _fail(f"{label}_duplicate_key:{key}")
            result[key] = value
        return result

    try:
        return json.loads(
            raw.decode("utf-8"),
            object_pairs_hook=unique_object,
            parse_constant=reject_constant,
            parse_float=parse_float,
        )
    except MxnInegiCpiExactSourceError:
        raise
    except (UnicodeDecodeError, json.JSONDecodeError, ValueError) as exc:
        raise MxnInegiCpiExactSourceError(f"{label}_invalid_json") from exc


def _canonical_utc(value: Any, *, label: str) -> dt.datetime:
    if type(value) is not str or not value.endswith("+00:00"):
        _fail(f"{label}_not_exact_utc_string")
    try:
        parsed = dt.datetime.fromisoformat(value)
    except ValueError as exc:
        raise MxnInegiCpiExactSourceError(f"{label}_invalid") from exc
    if parsed.tzinfo != UTC or parsed.isoformat() != value:
        _fail(f"{label}_not_canonical_utc")
    return parsed


def _http_date(value: Any, *, label: str) -> dt.datetime:
    if type(value) is not str:
        _fail(f"{label}_not_string")
    try:
        parsed = parsedate_to_datetime(value)
    except (TypeError, ValueError) as exc:
        raise MxnInegiCpiExactSourceError(f"{label}_invalid") from exc
    if parsed.tzinfo is None:
        _fail(f"{label}_naive")
    return parsed.astimezone(UTC)


def _workspace_path(relative_path: str) -> Path:
    if type(relative_path) is not str:
        _fail("archive_path_not_string")
    relative = Path(relative_path)
    if relative.is_absolute() or ".." in relative.parts:
        _fail("archive_path_not_workspace_relative")
    candidate = (_WORKSPACE_ROOT / relative).absolute()
    try:
        candidate.relative_to(_WORKSPACE_ROOT)
    except ValueError as exc:
        raise MxnInegiCpiExactSourceError("archive_path_escaped_workspace") from exc
    return candidate


def _file_identity(value: os.stat_result) -> tuple[int, int, int, int, int]:
    return (
        int(value.st_dev),
        int(value.st_ino),
        int(value.st_size),
        int(value.st_mtime_ns),
        int(value.st_nlink),
    )


def _assert_no_reparse_components(path: Path) -> None:
    current = Path(path.anchor)
    for part in path.parts[1:]:
        current = current / part
        try:
            value = os.lstat(current)
        except OSError as exc:
            raise MxnInegiCpiExactSourceError("pinned_file_component_missing") from exc
        if stat.S_ISLNK(value.st_mode):
            _fail("pinned_file_symlink_component_forbidden")
        attributes = int(getattr(value, "st_file_attributes", 0))
        reparse = int(getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x400))
        if attributes & reparse:
            _fail("pinned_file_reparse_component_forbidden")


def _read_exact_pinned_file(
    path: str | Path,
    *,
    expected_path: str | Path,
    expected_bytes: int,
    expected_sha256: str,
    require_read_only: bool = True,
) -> bytes:
    requested = Path(path).absolute()
    expected = Path(expected_path).absolute()
    if os.path.normcase(str(requested)) != os.path.normcase(str(expected)):
        _fail("pinned_file_path_substitution")
    _assert_no_reparse_components(requested)
    try:
        if requested.resolve(strict=True) != expected.resolve(strict=True):
            _fail("pinned_file_resolved_path_mismatch")
    except OSError as exc:
        raise MxnInegiCpiExactSourceError("pinned_file_missing") from exc
    before = os.lstat(requested)
    if not stat.S_ISREG(before.st_mode):
        _fail("pinned_file_not_regular")
    if before.st_nlink != 1:
        _fail("pinned_file_hardlink_forbidden")
    if require_read_only:
        if os.name == "nt":
            readonly = int(getattr(stat, "FILE_ATTRIBUTE_READONLY", 0x1))
            attributes = int(getattr(before, "st_file_attributes", 0))
            if attributes & readonly == 0:
                _fail("pinned_file_not_read_only")
        elif before.st_mode & (stat.S_IWUSR | stat.S_IWGRP | stat.S_IWOTH):
            _fail("pinned_file_not_read_only")
    with requested.open("rb") as handle:
        opened_before = os.fstat(handle.fileno())
        if _file_identity(opened_before) != _file_identity(before):
            _fail("pinned_file_swapped_before_open")
        raw = handle.read()
        opened_after = os.fstat(handle.fileno())
    after = os.lstat(requested)
    if _file_identity(opened_before) != _file_identity(opened_after):
        _fail("pinned_file_changed_while_reading")
    if _file_identity(opened_after) != _file_identity(after):
        _fail("pinned_file_path_swapped_after_read")
    if type(expected_bytes) is not int or isinstance(expected_bytes, bool):
        _fail("expected_bytes_not_exact_int")
    if len(raw) != expected_bytes:
        _fail("pinned_file_byte_count_mismatch")
    if type(expected_sha256) is not str or not re.fullmatch(r"[0-9a-f]{64}", expected_sha256):
        _fail("expected_sha256_invalid")
    if hashlib.sha256(raw).hexdigest() != expected_sha256:
        _fail("pinned_file_sha256_mismatch")
    return raw


def _normalized_pdf_text(raw: bytes) -> tuple[bytes, int]:
    if pypdf.__version__ != PDF_EXTRACTOR_VERSION:
        _fail(f"pdf_extractor_version_mismatch:{pypdf.__version__}")
    if sys.version.split()[0] != PYTHON_VERSION:
        _fail(f"python_pdf_runtime_version_mismatch:{sys.version.split()[0]}")
    try:
        reader = pypdf.PdfReader(io.BytesIO(raw), strict=True)
        pages: list[str] = []
        for page in reader.pages:
            text = page.extract_text(extraction_mode="layout") or ""
            text = text.replace("\r\n", "\n").replace("\r", "\n")
            text = "\n".join(line.rstrip(" \t") for line in text.split("\n"))
            pages.append(unicodedata.normalize("NFC", text).strip())
    except Exception as exc:
        raise MxnInegiCpiExactSourceError("pdf_extraction_failed") from exc
    return ("\n\f\n".join(pages).strip() + "\n").encode("utf-8"), len(reader.pages)


